"""``RESULTS.md``: every figure of the sweeps, with time-to-quality tables.

Built from the configs (to know which fits are expected), their results files and the
per-figure CSVs that ``python -m kmb plot`` writes. Run it after the plots:

    pixi run python -m kmb plot results/v1-gpu.jsonl results/v1-cpu.jsonl results/reference.jsonl
    pixi run python -m kmb report configs/v1-gpu.toml configs/v1-cpu.toml
"""

from __future__ import annotations

import csv
import json
import time
from collections import defaultdict
from pathlib import Path

from kmb import config as kconfig
from kmb import datasets

THRESHOLDS = (1e-2, 3e-3, 1e-3)


def _records(path: Path) -> list:
    out = []
    if path.exists():
        for line in path.read_text().splitlines():
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return out


def _progress(cfg) -> dict:
    """(dataset, k) -> (fits done, fits expected) for the config's own results file."""
    done = {(r["dataset"], r["k"], r["impl"], kconfig.canonical(r["params"]), r["seed"])
            for r in _records(cfg.results_path) if int(r.get("threads") or 0) == cfg.threads}
    out = {}
    for dataset, k, per_impl in kconfig.jobs_by_comparison(cfg):
        keys = {(dataset.label, k, job.impl, job.params_key, s)
                for jobs in per_impl.values() for job in jobs for s in job.seeds}
        out[(dataset.label, k)] = (len(keys & done), len(keys))
    return out


def _figure_label(cfg, records) -> tuple:
    """(machine label used in figure names, device) of a config's results."""
    rs = [r for r in records if r.get("status") == "ok"]
    if not rs:
        return None, None
    r = rs[-1]
    machine = r["machine"] if r["device"] == "gpu" else f"{r['machine']}-{cfg.threads}t"
    return machine, r["device"]


def _time_to_quality(csv_path: Path, device: str) -> list:
    rows = list(csv.DictReader(csv_path.open()))
    out = []
    for series in sorted({r["series"] for r in rows}):
        pts = [(float(r["fit_s"]), float(r["rel"])) for r in rows if r["series"] == series]
        cells = []
        for t in THRESHOLDS:
            ok = [f for f, rel in pts if rel <= t]
            cells.append(min(ok) if ok else None)
        out.append((series, device, cells, min(rel for _, rel in pts)))
    return out


def _fmt_s(v):
    if v is None:
        return "–"
    return f"{v:.2f} s" if v < 10 else f"{v:.0f} s"


def main(config_paths, plots="plots", out="RESULTS.md", reference="configs/reference.toml"):
    plots = Path(plots)
    cfgs = [kconfig.load(p) for p in config_paths]
    figures = []                               # (cfg, machine, device, progress)
    for cfg in cfgs:
        machine, device = _figure_label(cfg, _records(cfg.results_path))
        if machine:
            figures.append((cfg, machine, device, _progress(cfg)))
    order = [name for name in datasets.DATASETS
             if any(d.name == name for cfg in cfgs for d, _ in cfg.datasets)]
    ks = defaultdict(set)
    for cfg in cfgs:
        for d, k_list in cfg.datasets:
            ks[d.label].update(k_list)

    lines = [
        "# Results",
        "",
        f"Generated by `python -m kmb report` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}"
        f" from {', '.join(f'`{cfg.results_path}`' for cfg in cfgs)} and "
        "`results/reference.jsonl`. How to read the figures: "
        "[README](README.md#reading-the-plots). In short: fit time (initialization included, "
        "data already in memory or on the GPU) against inertia relative to the best known "
        "inertia of the (dataset, k), over all runs on any machine. One Pareto front per "
        "implementation; one point per setting, the median over seeds.",
        "",
        "Hardware: "
        + "; ".join(f"{device.upper()} `{machine}` (config `{cfg.path.name}`)"
                    for cfg, machine, device, _ in figures)
        + ". Time-to-quality tables give, for each implementation, the fastest setting whose "
        "median relative inertia is at or below each threshold (– if none).",
        "",
    ]
    partial = [(cfg, machine, label, k, d, e) for cfg, machine, device, prog in figures
               for (label, k), (d, e) in prog.items() if d < e]
    ref_partial = []
    if reference and Path(reference).exists():
        ref_partial = [(label, k, d, e) for (label, k), (d, e)
                       in _progress(kconfig.load(reference)).items() if d < e]
    if partial or ref_partial:
        items = [f"{label} k={k} on `{machine}` ({d}/{e} fits)"
                 for cfg, machine, label, k, d, e in partial]
        items += [f"reference runs for {label} k={k} ({d}/{e} fits; relative inertia can "
                  "still shift)" for label, k, d, e in ref_partial]
        lines += ["**Sweeps still running.** Incomplete: " + ", ".join(items) + ".", ""]
    lines += ["Datasets: " + ", ".join(f"[{name}](#{name})" for name in order), ""]

    for name in order:
        spec = datasets.DATASETS[name]
        n, d = spec.shape
        lines += [f"## {name}", "", f"{n:,} × {d}: {spec.source}. {spec.notes}", ""]
        for k in sorted(ks[name]):
            lines += [f"### {name}, k={k}", ""]
            table = []
            for cfg, machine, device, prog in figures:
                stem = f"{name}-k{k}-{machine}-{device}"
                done, expected = prog.get((name, k), (0, 0))
                if not (plots / f"{stem}.png").exists():
                    lines += [f"*{device.upper()} on `{machine}`: no results yet.*", ""]
                    continue
                note = "" if done >= expected else f" (partial: {done}/{expected} fits)"
                lines += [f"![{name}, k={k}, {device.upper()} on {machine}{note}]"
                          f"({plots / stem}.png)", ""]
                if note:
                    lines += [f"*{device.upper()}{note}.*", ""]
                table += _time_to_quality(plots / f"{stem}.csv", device)
            if table:
                head = " | ".join(f"≤ {t:g}" for t in THRESHOLDS)
                lines += [f"| implementation | device | {head} | best reached |",
                          "|---|---|" + "---|" * len(THRESHOLDS) + "---|"]
                for series, device, cells, best in sorted(
                        table, key=lambda r: (r[1], r[2][0] is None, r[2][0] or 0)):
                    lines.append(f"| {series} | {device.upper()} | "
                                 + " | ".join(_fmt_s(c) for c in cells) + f" | {best:.1e} |")
                lines.append("")
    Path(out).write_text("\n".join(lines))
    print(f"wrote {out} ({len(figures)} configs, {len(order)} datasets)")
